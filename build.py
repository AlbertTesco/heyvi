"""Generate the static site with Python's standard library."""

from html import escape
from hashlib import sha256
import json
from pathlib import Path
import re

from content import CASES, NAVIGATION, SERVICES, STEPS, TERMINAL_RUNS

ROOT = Path(__file__).resolve().parent
DIST = ROOT / "dist"
STYLES = ROOT / "styles"
DESIGN = json.loads((STYLES / "tokens.json").read_text(encoding="utf-8"))
TOKENS = {
    f"{group}-{name}": value
    for group, entries in DESIGN.items()
    if group != "breakpoints"
    for name, value in entries.items()
}
SITE_URL = re.compile(r'(\s(?:href|src)=")/(?!/)')
ICONS = {
    "spark": '<path d="M12 2v4m0 12v4M2 12h4m12 0h4M5 5l3 3m8 8 3 3M5 19l3-3m8-8 3-3"/><circle cx="12" cy="12" r="4"/>',
    "receipt": '<rect x="4" y="3" width="16" height="18" rx="2"/><path d="M8 7h8m-8 5h2m4 0h2m-8 4h2m4 0h2"/>',
    "chart": '<path d="M3 3v18h18M7 17v-3m5 3v-6m5 6V7m-9 4 4-4 2 1 5-5"/>',
    "people": '<circle cx="9" cy="8" r="3"/><path d="M2 21v-2a5 5 0 0 1 5-5h4a5 5 0 0 1 5 5v2m1-16a3 3 0 0 1 0 6m2 4a4 4 0 0 1 3 4v2"/>',
    "db": '<ellipse cx="12" cy="5.5" rx="8" ry="3"/><path d="M4 5.5v13c0 1.7 3.6 3 8 3s8-1.3 8-3v-13M4 12c0 1.7 3.6 3 8 3s8-1.3 8-3"/>',
    "nodes": '<rect x="9" y="3" width="6" height="5" rx="1"/><rect x="2" y="16" width="6" height="5" rx="1"/><rect x="16" y="16" width="6" height="5" rx="1"/><path d="M12 8v4M5 16v-4h14v4"/>',
    "browser": '<rect x="2" y="4" width="20" height="16" rx="2"/><path d="M2 8h20m-13 3-3 3 3 3m6-6 3 3-3 3"/>',
    "target": '<circle cx="12" cy="12" r="9"/><circle cx="12" cy="12" r="5"/><circle cx="12" cy="12" r="1"/>',
    "menu": '<path d="M3 6h18M3 12h18M3 18h18"/>',
    "chevron": '<path d="m9 5 7 7-7 7"/>',
    "down": '<path d="m5 9 7 7 7-7"/>',
    "download": '<path d="M12 3v12m-4-4 4 4 4-4M4 16v4h16v-4"/>',
}

CATEGORIES = (("all", "Все услуги"), ("agents", "ИИ-агенты"), ("systems", "1С и CRM"), ("digital", "Сайты и маркетинг"))


def icon(name, css_class="icon"):
    return (f'<svg class="{css_class}" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
            f'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">{ICONS[name]}</svg>')


def build_styles():
    template = (STYLES / "site.css").read_text(encoding="utf-8")
    css = re.sub(r"@media \(--([\w-]+)\)", lambda match: f"@media {DESIGN['breakpoints'][match[1]]}", template)
    declarations = "\n".join(f"  --{name}: {value};" for name, value in TOKENS.items())
    variables = set(re.findall(r"var\(--([\w-]+)", css + declarations))
    if missing := variables - TOKENS.keys():
        raise ValueError(f"Unknown design tokens: {', '.join(sorted(missing))}")

    assets = DIST / "assets"
    assets.mkdir(parents=True, exist_ok=True)
    banner = "/* Generated by build.py from styles/. */\n"
    (assets / "site.css").write_text(f"{banner}:root {{\n{declarations}\n}}\n\n{css}", encoding="utf-8")
    mark = (STYLES / "mark.svg").read_text(encoding="utf-8")
    mark = re.sub(r"\{\{([\w-]+)\}\}", lambda match: TOKENS[match[1]], mark)
    (assets / "mark.svg").write_text(mark, encoding="utf-8")


def route(slug):
    return f"/{slug}/" if slug else "/"


def brand():
    return ('<a class="brand" href="/" aria-label="ХЭЙВИ — главная">'
            '<img src="/assets/mark.svg" width="55" height="50" alt="">'
            '<span class="brand-wordmark"><strong>ХЭЙВИ</strong>'
            '<span>Интеллектуальные решения<br>для бизнеса</span></span></a>')


def nav(active):
    links = []
    for slug, label in NAVIGATION:
        current = ' aria-current="page"' if slug == active else ""
        links.append(f'<a href="{route(slug)}"{current}>{label}</a>')
    return "".join(links)


def button(label, href, style="primary"):
    return f'<a class="button button-{style}" href="{href}">{label}</a>'


def versioned_asset(name):
    version = sha256((DIST / "assets" / name).read_bytes()).hexdigest()[:12]
    return f"/assets/{name}?v={version}"


def write_page(slug, title, description, body, active=""):
    destination = DIST / slug / "index.html"
    destination.parent.mkdir(parents=True, exist_ok=True)
    full_title = f"{title} — ХЭЙВИ" if slug else "ХЭЙВИ — интеллектуальная автоматизация бизнеса"
    document = f"""<!doctype html>
<html lang="ru">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="description" content="{escape(description, quote=True)}">
<meta name="robots" content="noindex, nofollow">
<meta name="theme-color" content="{TOKENS['color-canvas']}">
<title>{escape(full_title)}</title>
<link rel="icon" href="/assets/mark.svg" type="image/svg+xml">
<link rel="preload" href="/assets/ibm-plex-sans-cyrillic.woff2" as="font" type="font/woff2" crossorigin>
<link rel="stylesheet" href="{versioned_asset('site.css')}">
<script src="{versioned_asset('site.js')}" defer></script>
</head>
<body>
<a class="skip-link" href="#main">Перейти к содержимому</a>
<header class="site-header">
  <div class="wrap header-inner">
    {brand()}
    <button class="menu-button" type="button" aria-expanded="false" aria-controls="top-nav" hidden>{icon("menu")} Меню</button>
    <nav class="top-nav" id="top-nav" aria-label="Основная навигация">
      {nav(active)}
      {button("Обсудить задачу", "/contact/", "outline nav-cta")}
    </nav>
  </div>
</header>
<main id="main" tabindex="-1">
{body}
</main>
<footer class="site-footer">
  <div class="wrap footer-main">
    {brand()}
    <nav aria-label="Разделы сайта">{nav(active)}</nav>
    <a href="/contact/">Подготовить бриф</a>
  </div>
  <div class="wrap footer-bottom">© ООО «ХЭЙВИ»</div>
</footer>
</body>
</html>
"""
    # Resolve internal URLs relative to each output page so the same build
    # works both at the domain root and under a GitHub Pages repository path.
    prefix = "../" * len(Path(slug).parts) if slug else "./"
    document = SITE_URL.sub(lambda match: match[1] + prefix, document)
    destination.write_text(document, encoding="utf-8")


def breadcrumbs(label, parent=None):
    middle = f'<a href="{route(parent[0])}">{parent[1]}</a>{icon("chevron")}' if parent else ""
    return (f'<nav class="breadcrumbs" aria-label="Путь к странице"><a href="/">Главная</a>'
            f'{icon("chevron")}{middle}<span aria-current="page">{label}</span></nav>')


def terminal_run(name):
    command, progress, result = TERMINAL_RUNS[name]
    return f"""<div class="terminal-trace" data-terminal-run aria-hidden="true">
      <div class="terminal-entry"><span>&gt;</span> heyvi demo {escape(command)}</div>
      <div class="terminal-progress"><span>·</span> {escape(progress)}</div>
      <div class="terminal-result"><span>✓</span> {escape(result)}</div>
    </div>"""


def page_intro(title, summary="", crumb=None, parent=None, action="", *, terminal):
    lead = f'<p class="lead">{summary}</p>' if summary else ""
    return f"""<section class="page-intro terminal-surface">
      <div class="wrap">
        {breadcrumbs(crumb or title, parent)}
        <div class="intro-grid">
          <div class="intro-copy"><h1>{title}</h1>{lead}{action}</div>
          {terminal_run(terminal)}
        </div>
      </div>
    </section>"""


def card(slug, item):
    return f"""<article class="service-card" data-category="{item['category']}">
      <a href="{route(slug)}">
        {icon(item["icon"], "icon service-icon")}
        <div class="service-card-copy"><h3>{item['name']}</h3><p>{item['description']}</p></div>
        {icon("chevron", "icon card-chevron")}
      </a>
    </article>"""


def cards(category=None):
    items = "".join(card(slug, item) for slug, item in SERVICES.items() if category is None or category == item["category"])
    return f'<div class="service-grid" id="service-list">{items}</div>'


def steps():
    items = "".join(
        f'<li><span class="step-number" aria-hidden="true">{number}</span><h3>{title}</h3><p>{description}</p></li>'
        for number, (title, description) in enumerate(STEPS, 1)
    )
    return f'<ol class="steps">{items}</ol>'


def case_cards(limit=None, featured=False):
    items = []
    for case in CASES[:limit]:
        if featured:
            action = f'<a class="text-link" href="/cases/#{case["id"]}">Смотреть сценарий<span class="visually-hidden"> «{case["title"]}»</span></a>'
        else:
            case_steps = "".join(f"<li>{step}</li>" for step in case["steps"])
            action = f"""<details class="case-details" data-scenario id="{case['id']}">
              <summary>Как это работает<span class="visually-hidden"> — {case['title']}</span></summary>
              <ol>{case_steps}</ol>
              <a class="text-link" href="{route(case['service'])}">{SERVICES[case['service']]['title']}</a>
            </details>"""
        items.append(f"""<article class="case-card">
          <img class="case-visual" src="/assets/case-{case['service']}.webp" width="960" height="320" alt="" loading="lazy" decoding="async">
          <div class="case-body">
            <h3>{case['title']}</h3>
            <p>{case['summary']}</p>
            {action}
          </div>
        </article>""")
    grid_class = "case-grid case-grid-featured" if featured else "case-grid"
    return f'<div class="{grid_class}">{"".join(items)}</div>'


def banner():
    return f"""<section class="wrap section banner-section">
      <div class="callout">
        <h2>С чего начнём?</h2>
        {button("Подготовить бриф", "/contact/")}
      </div>
    </section>"""


