def main():
    build_styles()
    write_page("", "Главная", "ХЭЙВИ создаёт ИИ-агентов для бухгалтерии, продаж и HR. Внедряем 1С и CRM, разрабатываем сайты и настраиваем маркетинг.", homepage())
    write_page("agents", "ИИ-агенты для бизнеса", "ИИ-агенты для бухгалтерии, продаж, подбора персонала и руководителей.", agents_page(), "agents")
    write_page("services", "Услуги", "Каталог услуг ХЭЙВИ: ИИ-агенты, автоматизация 1С и CRM, веб-разработка, SEO и маркетинг.", services_page(), "services")
    for slug, item in SERVICES.items():
        write_page(slug, item["title"], item["description"], service_page(slug, item))
    write_page("cases", "Кейсы и сценарии", "Примеры автоматизации продаж, бухгалтерии и маршрутизации заявок с сайта.", cases_page(), "cases")
    write_page("about", "О компании", "ООО «ХЭЙВИ»: ИИ-агенты, автоматизация процессов и связь с КАДИС.", about_page(), "about")
    write_page("contact", "Обсудить задачу", "Подготовьте и скачайте бриф для проекта автоматизации бизнеса.", contact_page())


if __name__ == "__main__":
    main()
